export function normalizeLanguage(value) {
  const base = String(value || '').toLowerCase().split('-')[0];
  return SUPPORTED_LANGUAGES.includes(base) ? base : '';
}

export function detectLanguage({ stored = '', navigatorLanguage = '' } = {}) {
  return normalizeLanguage(stored) || normalizeLanguage(navigatorLanguage) || 'en';
}

export function createI18n({ messages = MESSAGES, lang = 'en' } = {}) {
  let current = SUPPORTED_LANGUAGES.includes(lang) ? lang : 'en';
  // t(key) → string; t(key, { n }) interpolates `{n}` tokens; t(key, 'fallback')
  // returns the fallback string when the key is missing (back-compatible).
  function t(key, params) {
    const table = messages[current] || {};
    const en = messages.en || {};
    let value;
    if (Object.prototype.hasOwnProperty.call(table, key)) value = table[key];
    else if (Object.prototype.hasOwnProperty.call(en, key)) value = en[key];
    else return typeof params === 'string' ? params : key;
    if (params && typeof params === 'object') {
      value = value.replace(/\{(\w+)\}/g, (match, token) =>
        (Object.prototype.hasOwnProperty.call(params, token) ? String(params[token]) : match));
    }
    return value;
  }
  return {
    get lang() { return current; },
    setLang(next) {
      if (SUPPORTED_LANGUAGES.includes(next)) current = next;
      return current;
    },
    t,
  };
}

// Apply the current language to a DOM subtree via data-i18n / data-i18n-attr.
export function applyTranslations(root, t) {
  if (!root) return;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'));
  }
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.getAttribute('data-i18n-attr').split(';')) {
      const [attr, key] = pair.split(':').map((part) => (part || '').trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}

export function loadLanguage(storage, navigatorLanguage) {
  let stored = '';
  try {
    stored = storage?.getItem?.(STORAGE_KEY) || '';
  } catch {
    stored = '';
  }
  return detectLanguage({ stored, navigatorLanguage });
}

export function saveLanguage(storage, lang) {
  try {
    storage?.setItem?.(STORAGE_KEY, lang);
  } catch {
    /* storage may be unavailable (private mode); ignore */
  }
}

// Page-level bootstrap shared by every UI: pick the language, translate the
// static markup, keep `<html lang>` in sync, and bind the toggle button.
// `onRender` lets a page re-emit strings it renders imperatively (status chips
// and the like) whenever the language changes.
export function setupPageI18n({
  doc = globalThis.document,
  storage = globalThis.localStorage,
  navigatorLanguage = globalThis.navigator?.language || '',
  toggleId = 'langToggle',
  onRender = null,
} = {}) {
  const i18n = createI18n({ lang: loadLanguage(storage, navigatorLanguage) });
  function render() {
    if (doc?.documentElement) doc.documentElement.lang = i18n.lang;
    applyTranslations(doc, i18n.t);
    onRender?.(i18n.t, i18n.lang);
  }
  doc?.getElementById?.(toggleId)?.addEventListener?.('click', () => {
    i18n.setLang(i18n.lang === 'ja' ? 'en' : 'ja');
    saveLanguage(storage, i18n.lang);
    render();
  });
  render();
  return { i18n, t: i18n.t, render };
}
